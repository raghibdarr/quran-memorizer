// Assembles public/licenses.txt: every third-party text, data set and font Takrar ships, with
// the notice each licence asks to travel with it (Tanzil's copyright block, the MIT and OFL
// texts, QuranEnc's header). Settings links to it; the data files point to it.
// Run after changing data-sources/ or a bundled font: node scripts/build-licenses.mjs
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (...p) => readFileSync(join(root, ...p), 'utf8').replace(/\r\n/g, '\n');
const rule = (title) => `\n\n${'='.repeat(78)}\n${title}\n${'='.repeat(78)}\n\n`;

const tanzil = read('data-sources', 'tanzil', 'quran-uthmani.xml').match(/<!--([\s\S]*?)-->/)[1].trim();
const quranenc = read('data-sources', 'quranenc', 'english_saheeh.csv').match(/^"Translation Info:\n([\s\S]*?)",/)[1].trim();
const clear = read('data-sources', 'clearquran', 'clearquran-allah-edition.txt').match(/#={10,}[\s\S]*?#={10,}/)[0];
const digitalkhatt = read('data-sources', 'digitalkhatt', 'LICENSE').trim();
const amiri = read('public', 'fonts', 'AmiriQuran-OFL.txt').trim();
const mushaf = read('public', 'mushaf', 'NOTICE.txt').trim();
const translations = JSON.parse(read('src', 'data', 'translation-sources.json'));

const text = `Takrar: third-party texts, data and fonts
Generated by scripts/build-licenses.mjs. Takrar is free, with no ads and nothing for sale.
${rule('Quran text (Uthmani): Tanzil Project')}Used verbatim in every surah file (src/data/surah-N.json), the lessons, reader and search.
https://tanzil.net

${tanzil}
${rule(`English translation: ${translations.saheeh.name}, from QuranEnc.com`)}Republished unchanged, footnotes included, under QuranEnc's terms: no changes, name QuranEnc
and the version, keep this header. ${translations.saheeh.url}

${quranenc}
${rule('English translation: The Clear Quran, by Talal Itani')}Translation by Talal Itani, ClearQuran.com. CC BY-ND 4.0
(https://creativecommons.org/licenses/by-nd/4.0/) with the author's additional permissions to
reformat and split by verse without changing any words.

${clear}
${rule('Tajweed colours: cpfair/quran-tajweed')}Tajweed rule data by Colin Fair, https://github.com/cpfair/quran-tajweed, licensed under the
Creative Commons Attribution 4.0 International License (https://creativecommons.org/licenses/by/4.0/).
Its ranges were carried onto Tanzil's current text by scripts/build-tajweed.mjs.
${rule('Word timings: quran-align')}Word-precise timings for EveryAyah recordings by Colin Fair, https://github.com/cpfair/quran-align
(release 2016-11-24), licensed under the Creative Commons Attribution 4.0 International License
(https://creativecommons.org/licenses/by/4.0/). Renumbered to Takrar's word list.
${rule("Word and ayah timings: Qur'anic Universal Audio (QUD)")}Timestamps by Qur'anic Universal Audio, https://github.com/QUD-Technologies/quranic-universal-audio,
licensed under the Creative Commons Attribution 4.0 International License. The recordings remain
the property of their reciters and are streamed from MP3Quran.net and QuranicAudio.com.
${rule('Recitations')}Per-ayah recordings stream from EveryAyah.com; surah recordings from MP3Quran.net and
QuranicAudio.com. Takrar doesn't host them; a surah you download is saved on your device only.
${rule('IndoPak text: DigitalKhatt')}The IndoPak Quran text in src/data comes from DigitalKhatt's 15-line IndoPak text
(https://github.com/DigitalKhatt/digitalkhatt.org).

${digitalkhatt}
${rule('Mushaf pages and the DigitalKhatt fonts')}${mushaf}
${rule('Arabic font: Amiri Quran')}Amiri Quran 1.003, https://github.com/aliftype/amiri, shipped unmodified.

${amiri}
${rule('Transliteration')}Written by Takrar from Tanzil's text (src/lib/transliterate.ts).
${rule('Word-by-word English meanings')}The word meanings are the Quranic Arabic Corpus word-by-word English as published by Quran.com
(https://corpus.quran.com). Permission to bundle them has been requested; until it's answered,
treat this as pending.
${rule('Voice check: Tilawa')}The on-device recitation model and phoneme corpus are Tilawa by Quran-Lab
(https://github.com/yazinsai/tilawa), under the Non-Profit License 1.2, shipped with the model
as models/tilawa/NPL-1.2.txt.
`;
writeFileSync(join(root, 'public', 'licenses.txt'), text);
console.log(`public/licenses.txt: ${text.length.toLocaleString()} characters`);

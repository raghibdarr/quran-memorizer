#!/usr/bin/env node
// Turns NOAA's pinned WMM coefficient file (data-sources/wmm/WMM2025.COF) into
// src/lib/qibla/wmm2025.ts, the table the app evaluates on the device.
//
//   node data-sources/wmm/build-wmm.mjs          write the module
//   node data-sources/wmm/build-wmm.mjs --check  fail if the module is out of date
//
// src/lib/qibla/declination.test.ts also parses the .COF and compares it with the
// module, so a hand edit to either side fails vitest.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const cofPath = path.join(here, 'WMM2025.COF');
const outPath = path.join(root, 'src', 'lib', 'qibla', 'wmm2025.ts');

export function parseCof(text) {
  const lines = text.split(/\r?\n/).filter((l) => l.trim());
  const [epochStr, model, released] = lines[0].trim().split(/\s+/);
  const rows = [];
  for (const line of lines.slice(1)) {
    if (/^9{10,}/.test(line.trim())) break;
    const [n, m, g, h, gd, hd] = line.trim().split(/\s+/).map(Number);
    rows.push([n, m, g, h, gd, hd]);
  }
  return { epoch: Number(epochStr), model, released, rows };
}

function render({ epoch, model, released, rows }) {
  const body = rows.map((r) => `  [${r.join(', ')}],`).join('\n');
  return `// GENERATED by data-sources/wmm/build-wmm.mjs from data-sources/wmm/WMM2025.COF.
// Do not edit by hand. World Magnetic Model ${model} (NOAA NCEI / British Geological
// Survey), released ${released}: public domain (US government work). See
// data-sources/wmm/SOURCE.md.

/** Model epoch (decimal year) */
export const WMM_EPOCH = ${epoch};
/** The model's stated life: valid from the epoch to five years after it */
export const WMM_VALID_UNTIL = ${epoch + 5};
export const WMM_MODEL = '${model}';

/** [n, m, g (nT), h (nT), g per year (nT/yr), h per year (nT/yr)], Schmidt semi-normalised */
export const WMM_COEFFICIENTS: ReadonlyArray<readonly [number, number, number, number, number, number]> = [
${body}
];
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const out = render(parseCof(fs.readFileSync(cofPath, 'utf8')));
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== out) {
      console.error('src/lib/qibla/wmm2025.ts is out of date: run node data-sources/wmm/build-wmm.mjs');
      process.exit(1);
    }
    console.log('wmm2025.ts matches WMM2025.COF');
  } else {
    fs.writeFileSync(outPath, out);
    console.log(`wrote ${path.relative(root, outPath)} (${parseCof(fs.readFileSync(cofPath, 'utf8')).rows.length} coefficient rows)`);
  }
}
